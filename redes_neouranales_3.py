import torch
import torch.nn as nn
import torch.optim as optim

# Definición de una red neuronal regularizada en PyTorch orientada al dataset MNIST
class RedMNISTRegularizada(nn.Module):
    def __init__(self):
        super().__init__()
        self.flatten = nn.Flatten()                  # Aplana la matriz de entrada de 28x28 a un vector de 784 elementos
        self.fc1 = nn.Linear(784, 256)               # Capa lineal densa que conecta las 784 entradas con 256 neuronas ocultas
        self.relu = nn.ReLU()                        # Función de activación ReLU no lineal
        self.dropout = nn.Dropout(0.30)              # Capa Dropout que apaga aleatoriamente el 30% de las conexiones
        self.fc2 = nn.Linear(256, 10)                # Capa de salida lineal con 10 neuronas para las clases (dígitos del 0 al 9)

    def forward(self, x):
        x = self.flatten(x)
        x = self.fc1(x)
        x = self.relu(x)
        x = self.dropout(x)
