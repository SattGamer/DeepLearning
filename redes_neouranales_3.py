# Función para crear modelos experimentales permitiendo personalizar el optimizador y la cantidad de neuronas
def crear_modelo_experimento(optimizador, units=128):
    modelo = keras.Sequential([
        layers.Input(shape=(28, 28)),                  # Capa de entrada para imágenes de 28x28 píxeles
        layers.Flatten(),                              # Aplana la matriz 2D en un vector unidimensional de 784 elementos
        layers.Dense(units, activation="relu"),        # Capa oculta con la cantidad de neuronas especificada y activación ReLU
        layers.Dense(10, activation="softmax")         # Capa de salida con 10 neuronas y activación softmax para clasificación multiclase
    ])

    # Compilación del modelo con el optimizador recibido por parámetro, función de pérdida y métrica de precisión
    modelo.compile(
        optimizer=optimizador,
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )
    return modelo

# Diccionario de fábricas de optimizadores que encapsula la creación de SGD con momentum, RMSprop y Adam
fabricas_optimizadores = {
    "SGD_momentum": lambda: keras.optimizers.SGD(
        learning_rate=0.01, momentum=0.9
    ),
    "RMSprop": lambda: keras.optimizers.RMSprop(
        learning_rate=0.001
    ),
    "Adam": lambda: keras.optimizers.Adam(
        learning_rate=0.001
    )
}

# Estructuras para almacenar los resultados comparativos y el historial de cada entrenamiento
resultados_opt = []
historias_opt = {}

# Itera sobre cada optimizador para entrenar un modelo independiente y evaluar su desempeño
for nombre, fabrica in fabricas_optimizadores.items():
    keras.backend.clear_session()   # Limpia la sesión previa de Keras para liberar memoria
    tf.random.set_seed(SEED)        # Restablece la semilla para garantizar pesos iniciales idénticos en cada modelo

    # Crea una nueva instancia del modelo con el optimizador actual
    modelo = crear_modelo_experimento(fabrica())

    # Entrena el modelo en silencio (verbose=0) durante 5 épocas
    historia = modelo.fit(
        x_train, y_train,
        validation_data=(x_dev, y_dev),
        epochs=5,
        batch_size=64,
        verbose=0
    )

    # Guarda el historial completo y registra las métricas finales de la última época
    historias_opt[nombre] = historia
    resultados_opt.append({
        "optimizador": nombre,
        "train_accuracy": historia.history["accuracy"][-1],
        "dev_accuracy": historia.history["val_accuracy"][-1],
        "dev_loss": historia.history["val_loss"][-1]
    })

