x_test  = x_test.astype("float32") / 255.0

print("Rango train:", x_train.min(), x_train.max())

# Función para calcular y mostrar la distribución y porcentaje de cada clase (dígitos 0-9)
def distribucion_clases(y, nombre):
    # Cuenta la frecuencia de cada dígito (asegurando 10 clases del 0 al 9)
    conteos = np.bincount(y, minlength=10)

    # Calcula el porcentaje que representa cada clase respecto al total
    porcentajes = conteos / len(y) * 100

    # Crea un DataFrame de Pandas para estructurar los resultados en formato tabular
    tabla = pd.DataFrame({
        "digito": np.arange(10),
        "cantidad": conteos,
        "porcentaje": np.round(porcentajes, 2)
    })

    # Muestra el nombre del conjunto y la tabla formateada
    print("\n", nombre)
    display(tabla)
    return tabla

# Analiza y muestra la distribución de clases para los conjuntos de entrenamiento, validación y prueba
dist_train = distribucion_clases(y_train, "TRAIN")
dist_dev   = distribucion_clases(y_dev, "DEV")
dist_test  = distribucion_clases(y_test, "TEST")

# Función para construir un modelo de red neuronal básico (baseline) totalmente conectado
def crear_modelo_baseline(units=128, optimizer=None):
    modelo = keras.Sequential([
        layers.Input(shape=(28, 28)),                  # Capa de entrada para las imágenes de 28x28 píxeles
        layers.Flatten(),                              # Aplanas las imágenes 2D (28x28) en un vector 1D (784 valores)
        layers.Dense(units, activation="relu"),        # Capa oculta densa con función de activación ReLU
        layers.Dense(10, activation="softmax")         # Capa de salida con 10 neuronas (una por cada dígito) y softmax para probabilidades
    ])

    # Si no se especifica un optimizador, se usa Adam por defecto con tasa de aprendizaje de 0.001
    if optimizer is None:
        optimizer = keras.optimizers.Adam(learning_rate=0.001)

    # Compilación del modelo configurando el optimizador, la función de pérdida y la métrica de evaluación
    modelo.compile(
        optimizer=optimizer,
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )
    return modelo

# Creación de la instancia del modelo baseline y despliegue de su estructura
modelo_base = crear_modelo_baseline()
modelo_base.summary()

# Entrenamiento del modelo baseline utilizando los datos de entrenamiento y validación
