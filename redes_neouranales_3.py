# Función para construir un modelo aplicando técnicas de regularización (L2 y Dropout)
def crear_modelo_regularizado():
    modelo = keras.Sequential([
        layers.Input(shape=(28, 28)),                  # Capa de entrada para imágenes de 28x28 píxeles
        layers.Flatten(),                              # Aplana la matriz 2D en un vector de 784 elementos
        layers.Dense(
            512, activation="relu",
            kernel_regularizer=regularizers.l2(1e-4)   # Capa oculta con regularización L2 para penalizar pesos grandes
        ),
        layers.Dropout(0.30),                          # Capa Dropout que apaga aleatoriamente el 30% de las neuronas
        layers.Dense(
            256, activation="relu",
            kernel_regularizer=regularizers.l2(1e-4)   # Segunda capa oculta con regularización L2
        ),
        layers.Dropout(0.30),                          # Segunda capa Dropout del 30%
        layers.Dense(10, activation="softmax")         # Capa de salida con 10 neuronas para clasificación multiclase
    ])

    # Compilación del modelo con Adam, pérdida para enteros y precisión como métrica
    modelo.compile(
        optimizer=keras.optimizers.Adam(0.001),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )
    return modelo

